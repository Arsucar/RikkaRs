def value_for(key: str, loc: str, en: dict, zh: dict) -> str:
    if loc == "values-zh":
        return zh.get(key) or MANUAL_ZH.get(key) or en[key]
    if loc == "values-zh-rTW":
        base = zh.get(key) or MANUAL_ZH.get(key) or en[key]
        return to_tw(base)
    if loc == "values-ja":
        return JA.get(key) or en[key]
    if loc == "values-ko-rKR":
        return KO.get(key) or en[key]
    if loc == "values-ru":
        return RU.get(key) or en[key]
    return en[key]


def main() -> None:
    en = StringsXmlParser.parse(RES / "values" / "strings.xml")
    zh = StringsXmlParser.parse(RES / "values-zh" / "strings.xml")
    for loc in ("values-zh", "values-zh-rTW", "values-ja", "values-ko-rKR", "values-ru"):
        path = RES / loc / "strings.xml"
        existing = StringsXmlParser.parse(path)
        missing = [k for k in en if k not in existing]
        added = 0
        for key in missing:
            val = value_for(key, loc, en, zh)
            try:
                StringsXmlParser.update_entry(path, key, val)
                added += 1
            except OSError as exc:
                print(f"FAIL {loc} {key}: {exc!r} val={val[:80]!r}")
                raise
        print(f"{loc}: added {added} keys")


if __name__ == "__main__":
    main()